import "dotenv/config";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { gemini31VoiceIds, voiceDefaults } from "../src/features/voice/validation";
import { gemini31SpeechText, pcmToWav } from "../src/features/voice/provider";

const text = "Привет! Рад знакомству. Послушай, как звучит мой голос: спокойно, ясно и естественно.";
const folder = "artifacts/voice-library-20261006";
await mkdir(folder, { recursive: true });
await mkdir("public/media/voice-samples", { recursive: true });
const key = process.env.AITUNNEL_API_KEY?.trim();
if (!key) throw new Error("AITUNNEL key missing");
const budget = Number(process.env.VOICE_LIBRARY_BUDGET_RUB || 30);
if (!Number.isFinite(budget) || budget <= 0 || budget > 40) throw new Error("Invalid library budget");
type Receipt = { voiceId: string; phase: string; costRub?: number; url?: string; bytes?: number; seconds?: number; status?: number };
const reports: Receipt[] = [];
for (const voiceId of gemini31VoiceIds.filter(id => id !== "gemini31:Kore")) {
  const marker = `${folder}/${voiceId.slice(9)}.json`;
  try { reports.push(JSON.parse(await readFile(marker, "utf8"))); } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
}
let cost = reports.reduce((sum, r) => sum + (r.costRub || 0), 0);
const queue = gemini31VoiceIds.filter(id => id !== "gemini31:Kore" && !reports.some(r => r.voiceId === id));
let reserved = 0;
async function worker() {
  while (queue.length) {
    if (cost + reserved + 1.5 > budget) return;
    const voiceId = queue.shift()!;
    const name = voiceId.slice(9), marker = `${folder}/${name}.json`;
    const report: Receipt = { voiceId, phase: "started" };
    await writeFile(marker, JSON.stringify(report), { flag: "wx" });
    reports.push(report); reserved += 1.5;
    try {
      const settings = { ...voiceDefaults, voiceId };
      const response = await fetch("https://api.aitunnel.ru/v1/audio/speech", {
        method: "POST", headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
        body: JSON.stringify({ model: "gemini-3.1-flash-tts-preview", voice: name,
          input: gemini31SpeechText(settings, text), response_format: "pcm" }),
        signal: AbortSignal.timeout(60000), redirect: "error",
      });
      report.status = response.status;
      const charge = response.headers.get("cost-rub");
      if (charge === null && response.ok) throw new Error("Missing cost header; stop for budget review");
      report.costRub = Number(charge || 0); cost += report.costRub;
      if (!response.ok || !/^audio\/(pcm|l16|wav|x-wav)(;|$)/i.test(response.headers.get("content-type") || "")) {
        await response.body?.cancel(); throw new Error(`HTTP ${response.status}`);
      }
      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes.length > 8 * 1024 * 1024) throw new Error("Oversized sample");
      const wav = pcmToWav(bytes, response.headers.get("content-type") || "");
      const filename = `gemini31-${name.toLowerCase()}.wav`;
      await writeFile(`public/media/voice-samples/${filename}`, wav);
      Object.assign(report, { phase: "saved", url: `/media/voice-samples/${filename}`, bytes: wav.length, seconds: (wav.length - 44) / 48000 });
      console.log(JSON.stringify(report));
    } catch (error) {
      report.phase = "failed";
      console.log(name, error instanceof Error ? error.message : "failed");
      // Ambiguous charges stop further submissions; failed UUIDs are never retried.
      queue.length = 0;
      process.exitCode = 1;
    } finally {
      reserved -= 1.5;
      await writeFile(marker, JSON.stringify(report));
    }
  }
}
await Promise.all([worker(), worker(), worker()]);
const samples = Object.fromEntries(reports.filter(r => r.phase === "saved").map(r => [r.voiceId, [{ label: "Обычная подача", url: r.url }]]));
await writeFile("src/features/voice/generated-samples.ts", `// Generated by scripts/generate-voice-library.ts. No runtime API calls.\nexport const generatedVoiceSamples = ${JSON.stringify(samples, null, 2)};\n`);
const summary = { ready: Object.keys(samples).length, costRub: Number(cost.toFixed(4)), remaining: queue.length, text };
await writeFile(`${folder}/summary.json`, JSON.stringify(summary, null, 2));
console.log("SUMMARY", JSON.stringify(summary));
