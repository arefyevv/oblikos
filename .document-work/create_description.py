def link(label, url):
    para = doc.add_paragraph()
    rel = para.part.relate_to(url, 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink', is_external=True)
    el = OxmlElement('w:hyperlink')
    el.set(qn('r:id'), rel)
    run = OxmlElement('w:r')
    prop = OxmlElement('w:rPr')
    col = OxmlElement('w:color'); col.set(qn('w:val'), '31566C'); prop.append(col)
    run.append(prop)
    txt = OxmlElement('w:t'); txt.text = label; run.append(txt)
    el.append(run); para._p.append(el)

